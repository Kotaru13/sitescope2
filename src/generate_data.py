def generate(seed=SEED, n=N_SYNTH):
    rnd = random.Random(seed)
    base = date(2023, 1, 1)
    docs = []
    for i in range(1, n + 1):
        cat = rnd.choice(list(TOPICS))
        topic = rnd.choice(TOPICS[cat])
        title = f"{rnd.choice(VERBS)}: {topic}"
        desc = f"{topic}. {rnd.choice(FILL).capitalize()}; {rnd.choice(FILL)}."
        docs.append({"id": f"doc-{i:04d}", "title": title, "description": desc, "category": cat,
                     "tags": [cat, topic.split()[0].lower()],
                     "published_at": (base + timedelta(days=rnd.randint(0, 1000))).isoformat()})
    for id_, t, d, c, tags, p in MANUAL:
        docs.append({"id": id_, "title": t, "description": d, "category": c, "tags": tags, "published_at": p})
    return docs

def main():
    docs = generate()
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for d in docs:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    print(f"Записано {len(docs)} документов -> {OUT}")

if __name__ == "__main__":
    main()
